export function translateSkillStudio(locale: Locale, key: SkillStudioTranslationKey, params: TranslationParams = {}): string {
  return dictionaries[locale][key].replace(/\{([A-Za-z0-9_]+)\}/g, (match, name: string) => params[name] === undefined ? match : String(params[name]));
}

