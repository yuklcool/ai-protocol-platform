"""GitHub-only disposable PostgreSQL: the SQL determines facts, not a fixed service."""

import json
import os
from pathlib import Path
from types import SimpleNamespace

import asyncpg
import pytest

from adk.a2ui_lighting_render import lighting_to_a2ui
from lighting.results import LightingResult
from tests.fixtures.lighting_results import fixture


@pytest.mark.asyncio
async def test_sql_filters_change_the_rendered_facts():
    assert os.environ.get('GITHUB_ACTIONS') == 'true'
    connection = await asyncpg.connect(os.environ['LIGHTING_TEST_DATABASE_URL'])
    try:
        await connection.execute('CREATE TEMP TABLE ci_readings (day date, lamps integer)')
        await connection.execute("INSERT INTO ci_readings VALUES ('2026-10-24', 9), ('2026-10-25', 17)")
        for day, expected in [('2026-10-24', 9), ('2026-10-25', 17)]:
            # Synthetic schema only. Production SQL is generated by the safety Skill.
            sql = f"""SELECT $1::jsonb || jsonb_build_object(
                'schema_version', 'lighting-query/v1',
                'metrics', jsonb_build_array(jsonb_build_object('label', '纳入灯数', 'value', sum(lamps)))
            ) AS payload FROM ci_readings WHERE day = '{day}'"""
            async with connection.transaction(readonly=True):
                rows = await connection.fetch(sql, json.dumps(fixture()))
            response = {'ok': True, 'meta': {'truncated': False}, 'rows': [dict(row) for row in rows]}
            context = SimpleNamespace(state={
                'temp:_a2ui_tool_args': {'sql': sql}, 'temp:_lighting_mcp_server': 'ci-sql',
            })
            messages = lighting_to_a2ui({'structuredContent': {'result': response}}, context)
            root = messages[-1]['updateDataModel']['value']
            assert root['status'] != 'error'
            assert root['metrics'][0]['value'] == expected
            assert root['server_id'] == 'ci-sql'
    finally:
        await connection.close()


def test_all_six_skills_use_the_existing_safety_skill():
    sources = list((Path(__file__).resolve().parents[2] / 'skills').glob('lighting-*/SKILL.md'))
    assert len(sources) == 6
    for source in sources:
        instructions = source.read_text()
        runtime = (source.parent / 'references/runtime.md').read_text()
        schema = json.loads((source.parent / 'references/presentation.schema.json').read_text())
        assert schema == LightingResult.model_json_schema()
        assert 'sql-safe-query' in instructions
        assert 'sql_query_readonly' in instructions
        assert 'lighting-query/v1' in runtime
        assert 'payload' in runtime and 'max_rows=1' in runtime
